#!/usr/bin/env python3
"""Hold the scoreboard to what has already been achieved.

tools/progress.py scores the build against the retail binaries and writes
out/progress/. This compares that run with the baseline recorded in
progress/ -- the list of every function already byte-identical
(progress/identical.txt) and the figures they add up to
(progress/summary.json) -- and with the progress table in README.md.

  ratchet.py check [--complete] [--covered]
      Fails if a function recorded as byte-identical no longer is, if a
      target's identical byte count went down, if its count of unwritten
      or unplaced functions went up, or if README.md's table is not the
      one progress/summary.json renders. New identical functions pass,
      with a reminder to record them. --covered also fails unless every
      target has no unwritten and no unplaced function (full coverage:
      everything written and placed, near or identical); --complete
      unless every scored function is identical: the finish line.
  ratchet.py update [--accept-losses]
      Records the run as the new baseline and rewrites README.md's table.
      Refuses a run that lost a recorded function unless --accept-losses
      is given, and a run that did not score the shipped libraries (when
      progress/targets.py has any), since the baseline has to cover every
      target.
  ratchet.py readme
      Rewrites README.md's table from progress/summary.json only.

`make progress` is `progress.py` then `ratchet.py check`; `make
progress-update` is `progress.py` then `ratchet.py update`.
"""
import csv
import json
import math
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUN = "out/progress"
BASE = "progress"
README = "README.md"
BEGIN = "<!-- progress:begin -->"
END = "<!-- progress:end -->"

# Coverage: shipped functions nothing of ours is placed at, and functions of
# ours linked into our image that no shipped function is placed for
# (tools/progress.py). Neither may go up.
COVERAGE = ("unwritten", "unplaced")

sys.path.insert(0, os.path.join(REPO, "progress"))
sys.dont_write_bytecode = True     # no progress/__pycache__
import targets as cfg  # noqa: E402

# The README's rows, in progress/targets.py's order: (label, what it is, the
# targets it adds up). Libraries scored on their own (cfg.LIBS) share one
# row.
ROWS = [("`%s`" % t["label"], t["what"], [t["label"]])
        for t in cfg.TARGETS if t["kind"] != "resources"]
if cfg.LIBS:
    ROWS.append(("libraries", "the shared libraries", [l for l, _p in cfg.LIBS]))
# Rows listed after ROWS but left out of the total: resource-only images,
# scored resource by resource (tools/progress.py, rows_for_resources). Their
# data is not code, so it is not added to the total.
RES_ROWS = [("`%s`" % t["label"], t["what"], [t["label"]])
            for t in cfg.TARGETS if t["kind"] == "resources"]
# what names the shipped libraries' directory, for the messages below
LIBS_ENV = cfg.SHIPPED_ENV or "the shipped libraries' variable"


def load_run():
    try:
        summary = json.load(open(os.path.join(RUN, "summary.json")))
        rows = list(csv.DictReader(open(os.path.join(RUN, "functions.csv"))))
    except OSError:
        sys.exit("ratchet.py: no scoreboard run in %s/ -- run tools/progress.py "
                 "(or `make progress`)" % RUN)
    return summary, rows


def identical_set(rows):
    return {(r["target"], r["function"]) for r in rows
            if r["status"] == "identical"}


def load_baseline():
    ident = set()
    if not os.path.exists(os.path.join(BASE, "identical.txt")):
        return ident, {"targets": {}}       # nothing recorded yet
    for line in open(os.path.join(BASE, "identical.txt")):
        line = line.rstrip("\n")
        if line and not line.startswith("#"):
            t, f = line.split("\t", 1)
            ident.add((t, f))
    return ident, json.load(open(os.path.join(BASE, "summary.json")))


def pct_floor(n, d):
    """Percent to one decimal, rounded DOWN: 99.96% must not read 100.0%."""
    return math.floor(1000 * n / d) / 10 if d else 0.0


def bar(n, d, width=20):
    full = int(width * n / d) if d else 0
    return "█" * full + "░" * (width - full)


def render(summary):
    t = summary["targets"]
    out = [BEGIN,
           "<!-- generated by tools/ratchet.py from progress/summary.json: "
           "edit neither by hand; `make progress-update` rewrites both -->",
           "",
           "| Binary | | Byte-identical functions | Byte-identical code | "
           "| Unwritten | Unplaced |",
           "|---|---|--:|--:|---|--:|--:|"]
    tot = {"identical": 0, "funcs": 0, "bytes_identical": 0, "bytes_total": 0,
           "unwritten": 0, "unplaced": 0}
    for label, what, names in ROWS:
        agg = {k: sum(t[n].get(k, 0) for n in names) for k in tot}
        for k in tot:
            tot[k] += agg[k]
        out.append(
            f"| {label} | {what} | {agg['identical']:,} / {agg['funcs']:,} | "
            f"{agg['bytes_identical']:,} / {agg['bytes_total']:,} bytes | "
            f"`{bar(agg['bytes_identical'], agg['bytes_total'])}` "
            f"{pct_floor(agg['bytes_identical'], agg['bytes_total'])}% | "
            f"{agg['unwritten']:,} | {agg['unplaced']:,} |")
    for label, what, names in RES_ROWS:
        agg = {k: sum(t[n].get(k, 0) for n in names) for k in tot}
        if not agg["funcs"]:                # an empty resource directory
            out.append(f"| {label} | {what}, not in the total | no "
                       f"resources | -- | -- | -- | -- |")
            continue
        out.append(
            f"| {label} | {what}, not in the total | {agg['identical']:,} / "
            f"{agg['funcs']:,} resources | "
            f"{agg['bytes_identical']:,} / {agg['bytes_total']:,} bytes | "
            f"`{bar(agg['bytes_identical'], agg['bytes_total'])}` "
            f"{pct_floor(agg['bytes_identical'], agg['bytes_total'])}% | "
            f"{agg['unwritten']:,} | -- |")
    out.append(
        f"| **All** | | **{tot['identical']:,} / {tot['funcs']:,}** | "
        f"**{tot['bytes_identical']:,} / {tot['bytes_total']:,} bytes** | "
        f"`{bar(tot['bytes_identical'], tot['bytes_total'])}` "
        f"**{pct_floor(tot['bytes_identical'], tot['bytes_total'])}%** | "
        f"**{tot['unwritten']:,}** | **{tot['unplaced']:,}** |")
    out.append(END)
    return "\n".join(out)


def readme_block(text):
    try:
        i = text.index(BEGIN)
        j = text.index(END, i) + len(END)
    except ValueError:
        sys.exit("ratchet.py: %s has no %s ... %s block" % (README, BEGIN, END))
    return i, j


def write_readme(summary):
    text = open(README, encoding="utf-8").read()
    i, j = readme_block(text)
    new = text[:i] + render(summary) + text[j:]
    if new != text:
        open(README, "w", encoding="utf-8").write(new)
        print(f"ratchet.py: rewrote the progress table in {README}")


def compare(run_summary, rows):
    """(lost, gained, byte drops, scored targets) against the baseline."""
    base_ident, base_summary = load_baseline()
    scored = set(run_summary["targets"])
    now = identical_set(rows)
    lost = sorted(k for k in base_ident if k[0] in scored and k not in now)
    gained = sorted(k for k in now if k not in base_ident)
    drops, rises = [], []
    for label in sorted(scored):
        b = base_summary["targets"].get(label)
        n = run_summary["targets"][label]
        if b and n["bytes_identical"] < b["bytes_identical"]:
            drops.append((label, b["bytes_identical"], n["bytes_identical"]))
        for k in COVERAGE:
            if b and k in b and n.get(k, 0) > b[k]:
                rises.append((label, k, b[k], n[k]))
    return lost, gained, drops, rises, base_summary


def table(base_summary, run_summary):
    print(f"{'target':<18} {'identical (recorded -> now)':>30} "
          f"{'identical bytes (recorded -> now)':>36} "
          f"{'unwritten':>14} {'unplaced':>14}")
    for label in sorted(run_summary["targets"]):
        n = run_summary["targets"][label]
        b = base_summary["targets"].get(label, {"identical": 0,
                                                "bytes_identical": 0})
        df = n["identical"] - b["identical"]
        db = n["bytes_identical"] - b["bytes_identical"]
        cov = " ".join(f"{str(b.get(k, '-')):>6} -> {n.get(k, 0):<4}"
                       for k in COVERAGE)
        print(f"{label:<18} {b['identical']:>12} -> {n['identical']:>6} "
              f"{'(%+d)' % df if df else '':>7} "
              f"{b['bytes_identical']:>14} -> {n['bytes_identical']:>8} "
              f"{'(%+d)' % db if db else '':>9} {cov}")


def cmd_check(complete, covered=False):
    run_summary, rows = load_run()
    lost, gained, drops, rises, base_summary = compare(run_summary, rows)
    table(base_summary, run_summary)
    print()
    ok = True
    if not run_summary.get("libraries_scored"):
        print("note: the shipped libraries were not scored (%s is not "
              "set), so their recorded functions were not checked" % LIBS_ENV)
    if lost:
        ok = False
        print(f"FAIL: {len(lost)} function(s) recorded as byte-identical no "
              f"longer are:")
        for t, f in lost:
            print(f"  {t}\t{f}")
    for label, was, now in drops:
        ok = False
        print(f"FAIL: {label}: byte-identical code went down, {was} -> {now} "
              f"bytes")
    for label, k, was, now in rises:
        ok = False
        print(f"FAIL: {label}: {k} functions went up, {was} -> {now} "
              f"(tools/progress.py --{k}={label} lists them)")
    text = open(README, encoding="utf-8").read()
    i, j = readme_block(text)
    if text[i:j] != render(base_summary):
        ok = False
        print(f"FAIL: {README}'s progress table does not match "
              f"{BASE}/summary.json -- run tools/ratchet.py readme")
    if complete:
        short = [(k, v) for k, v in sorted(run_summary["targets"].items())
                 if v["identical"] < v["funcs"]]
        for label, v in short:
            ok = False
            print(f"FAIL (--complete): {label}: {v['identical']} of "
                  f"{v['funcs']} functions byte-identical")
        if not run_summary.get("libraries_scored"):
            ok = False
            print("FAIL (--complete): the libraries were not scored")
    if covered:
        for label, v in sorted(run_summary["targets"].items()):
            for k in COVERAGE:
                if v.get(k, 0):
                    ok = False
                    print(f"FAIL (--covered): {label}: {v[k]} {k} "
                          f"function(s)")
        if not run_summary.get("libraries_scored"):
            ok = False
            print("FAIL (--covered): the libraries were not scored")
    if gained:
        print(f"{len(gained)} function(s) newly byte-identical, not yet "
              f"recorded: `make progress-update` records them")
    if ok:
        print("PASS: every function recorded as byte-identical still is")
    return 0 if ok else 1


def cmd_update(accept_losses):
    run_summary, rows = load_run()
    if not run_summary.get("libraries_scored"):
        sys.exit("ratchet.py: this run did not score the libraries "
                 "(%s is not set); the baseline must cover every "
                 "target, so it was not updated" % LIBS_ENV)
    lost, gained, drops, rises, base_summary = compare(run_summary, rows)
    if (lost or drops or rises) and not accept_losses:
        for t, f in lost:
            print(f"  lost: {t}\t{f}")
        for label, was, now in drops:
            print(f"  {label}: {was} -> {now} identical bytes")
        for label, k, was, now in rises:
            print(f"  {label}: {was} -> {now} {k} functions")
        sys.exit(f"ratchet.py: this run lost {len(lost)} recorded "
                 f"function(s), {len(drops)} target(s) lost identical bytes "
                 f"and {len(rises)} coverage count(s) went up; not updating. "
                 f"Fix them, or pass --accept-losses (ACCEPT_LOSSES=1) if "
                 f"the loss is right")
    ident = sorted(identical_set(rows))
    with open(os.path.join(BASE, "identical.txt"), "w") as f:
        f.write("# Every function the scoreboard has verified byte-identical to "
                "the retail binaries\n# (target<TAB>function). Written by "
                "tools/ratchet.py update; `make progress`\n# fails if one of "
                "them stops matching.\n")
        for t, fn in ident:
            f.write(f"{t}\t{fn}\n")
    with open(os.path.join(BASE, "summary.json"), "w") as f:
        json.dump(run_summary, f, indent=2, sort_keys=True)
        f.write("\n")
    table(base_summary, run_summary)
    print(f"\nrecorded {len(ident)} byte-identical functions "
          f"({len(gained)} new, {len(lost)} lost) in {BASE}/")
    write_readme(run_summary)
    return 0


def main():
    os.chdir(REPO)
    args = sys.argv[1:]
    cmd = args[0] if args else ""
    if cmd == "check":
        sys.exit(cmd_check("--complete" in args, "--covered" in args))
    if cmd == "update":
        sys.exit(cmd_update("--accept-losses" in args))
    if cmd == "readme":
        _ident, base_summary = load_baseline()
        write_readme(base_summary)
        return
    sys.exit(__doc__)


if __name__ == "__main__":
    main()
